"""Reproduce the declared input families and both parameter regimes."""

from fractions import Fraction
import hashlib
import json
from pathlib import Path
import platform
import subprocess
import sys
from format_table import upper_scientific
from record_format import DEFAULT_INITIAL, input_from_coefficients


def cases():
    return {
        "E1-baseline": DEFAULT_INITIAL,
        "E2-constant": [Fraction(1,2)],
        "E3-signed": [Fraction(3,8),Fraction(-1,32),Fraction(1,128),Fraction(-1,1024)],
        "E4-boundary": [Fraction(31,32),Fraction(1,128)],
        "E5-high-tail": [Fraction(1,4)]+[Fraction(0)]*19+[Fraction(1,2*4**20)],
        "E6-den8": [Fraction(1,3),Fraction(1,4*((1<<8)+1)),Fraction(-1,16*((1<<8)+1))],
        "E6-den128": [Fraction(1,3),Fraction(1,4*((1<<128)+1)),Fraction(-1,16*((1<<128)+1))],
        "E7-sparse": [Fraction(1,4)]+[Fraction(0)]*5+[Fraction(1,4**7)],
        "E7-dense": [Fraction((-1)**j,8*4**j) for j in range(7)],
    }


def main():
    source = Path(__file__).resolve().parent
    results = source.parents[1]/"results"/"neumann"
    matrix = results/"matrix"
    matrix.mkdir(parents=True, exist_ok=True)
    inputs = cases()
    jobs = [(name,m,"practical") for name in inputs for m in (1,4,8,12)]
    jobs += [("E2-constant",1,"guaranteed"),("E2-constant",2,"guaranteed"),
             ("E3-signed",1,"guaranteed")]
    rows = []
    for name, coefficients in inputs.items():
        (matrix/(name+".input.json")).write_text(
            json.dumps(input_from_coefficients(coefficients),indent=2)+"\n",encoding="utf-8")
    for name,m,mode in jobs:
        stem = f"{name}-m{m}-{mode}"
        input_file = matrix/(name+".input.json")
        record_file = matrix/(stem+".record.json")
        report_file = matrix/(stem+".report.json")
        command = [sys.executable,"-B",str(source/"produce.py"),"--input",str(input_file),
                   "--m",str(m),"--mode",mode,"--output",str(record_file)]
        if mode == "practical":
            command += ["--steps","16","--degree",str(m+8)]
        production = json.loads(subprocess.run(command,check=True,text=True,capture_output=True).stdout)
        command = [sys.executable,"-B",str(source/"verify.py"),str(record_file),
                   "--input",str(input_file),"--expected-m",str(m),"--report",str(report_file)]
        verification = json.loads(subprocess.run(command,check=True,text=True,capture_output=True).stdout)
        row = {"case":name,"input_file":input_file.name,"record_file":record_file.name,
               "report_file":report_file.name,"m":m,"mode":mode,
               "input_bytes":input_file.stat().st_size,"record_bytes":record_file.stat().st_size,
               "producer_seconds":production["producer_seconds"],
               "verifier_seconds":verification["verifier_seconds"],
               "record_sha256":hashlib.sha256(record_file.read_bytes()).hexdigest()}
        for key in ("cutoff","steps","degree","fractional_bits","initial_error_Alin",
                    "max_residual_Alin","max_polynomial_A4","spatial_error",
                    "time_and_rounding_error","total_error","target","endpoint_observations"):
            row[key] = verification[key]
        if mode == "guaranteed":
            row["theorem_strong_checks"] = verification["theorem_strong_checks"]
            assert all(verification["theorem_strong_checks"][key]
                       for key in ("initial_below_xi","residual_below_xi"))
        if name == "E2-constant":
            exact = Fraction(16,31)
            center = Fraction(verification["endpoint_observations"]["mean"]["exact"])
            row["exact_constant_error"] = str(abs(center-exact))
            assert abs(center-exact) <= Fraction(verification["total_error"]["exact"])
        rows.append(row)
        print(stem, "ACCEPT", f'{row["producer_seconds"]:.3f}/{row["verifier_seconds"]:.3f}s',flush=True)
    summary = {"python":platform.python_version(),"platform":platform.platform(),
               "arithmetic":"exact integers and rationals; times are descriptive",
               "practical_parameters":"J=16, r=m+8, b=64, K=m+3",
               "rows":rows}
    (results/"matrix_summary.json").write_text(json.dumps(summary,indent=2)+"\n",encoding="utf-8")
    lines = ["% Generated by run_matrix.py; all error displays are rounded upward.",
             r"\newcommand{\NeumannMatrixRows}{%"]
    for row in rows:
        if row["m"] != 8 or row["mode"] != "practical":
            continue
        err = upper_scientific(Fraction(row["total_error"]["exact"]))[0]
        res = upper_scientific(Fraction(row["max_residual_Alin"]["exact"]))[0]
        lines.append(" & ".join([row["case"],str(row["input_bytes"]),res,err,
                     str(row["record_bytes"]),f'{row["producer_seconds"]:.3f}/{row["verifier_seconds"]:.3f}'])+r" \\")
    lines += ["}",r"\newcommand{\NeumannGuaranteedRows}{%"]
    for row in rows:
        if row["mode"] != "guaranteed":
            continue
        err = upper_scientific(Fraction(row["total_error"]["exact"]))[0]
        lines.append(" & ".join([row["case"],str(row["m"]),str(row["steps"]),str(row["degree"]),
                     str(row["fractional_bits"]),err,f'{row["producer_seconds"]:.3f}/{row["verifier_seconds"]:.3f}'])+r" \\")
    lines.append("}")
    (results/"matrix_rows.tex").write_text("\n".join(lines)+"\n",encoding="utf-8")


if __name__ == "__main__":
    main()
