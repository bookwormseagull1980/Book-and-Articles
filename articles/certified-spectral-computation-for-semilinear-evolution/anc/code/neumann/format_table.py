"""Generate manuscript rows with outward-rounded exact error bounds."""

from fractions import Fraction
import json
from pathlib import Path


def power_of_ten(exponent):
    return Fraction(10 ** exponent) if exponent >= 0 else Fraction(1, 10 ** (-exponent))


def upper_scientific(value, significant=4):
    """Return TeX and its exact value, rounded upward to significant digits."""
    value = Fraction(value)
    if value < 0 or significant < 1:
        raise ValueError("nonnegative bound and positive digit count required")
    if not value:
        return "$0$", Fraction(0)
    exponent = len(str(value.numerator)) - len(str(value.denominator))
    scale = power_of_ten(exponent)
    while value < scale:
        exponent -= 1
        scale /= 10
    while value >= 10 * scale:
        exponent += 1
        scale *= 10
    unit = power_of_ten(exponent - significant + 1)
    ratio = value / unit
    coefficient = (ratio.numerator + ratio.denominator - 1) // ratio.denominator
    if coefficient == 10 ** significant:
        coefficient //= 10
        exponent += 1
        unit *= 10
    digits = str(coefficient)
    mantissa = digits if significant == 1 else digits[0] + "." + digits[1:]
    rounded = coefficient * unit
    assert rounded >= value
    return "$" + mantissa + r"\times10^{" + str(exponent) + "}$", rounded


def render_rows(summary):
    lines = ["% Generated by anc/code/neumann/format_table.py; bounds rounded upward.",
             r"\newcommand{\NeumannResultRows}{%"]
    for row in summary["rows"]:
        residual, _ = upper_scientific(Fraction(row["max_residual_Alin"]["exact"]))
        error, _ = upper_scientific(Fraction(row["total_error"]["exact"]))
        cells = [str(row["m"]), str(row["cutoff"]), str(row["degree"]),
                 residual, error, str(row["record_bytes"]),
                 f'{row["producer_seconds"]:.3f}/{row["verifier_seconds"]:.3f}']
        lines.append(" & ".join(cells) + r" \\")
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_rows(summary, destination):
    destination.write_text(render_rows(summary), encoding="utf-8")


def main():
    results = Path(__file__).resolve().parents[2] / "results" / "neumann"
    summary = json.loads((results / "summary.json").read_text(encoding="utf-8"))
    destination = results / "table_rows.tex"
    write_rows(summary, destination)
    print(destination.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
